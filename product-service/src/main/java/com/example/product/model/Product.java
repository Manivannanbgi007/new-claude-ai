package com.example.product.model;

import org.springframework.data.annotation.Id;
import org.springframework.data.elasticsearch.annotations.DateFormat;
import org.springframework.data.elasticsearch.annotations.Document;
import org.springframework.data.elasticsearch.annotations.Field;
import org.springframework.data.elasticsearch.annotations.FieldType;
import org.springframework.data.elasticsearch.annotations.InnerField;
import org.springframework.data.elasticsearch.annotations.MultiField;
import org.springframework.data.elasticsearch.annotations.Setting;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * READ MODEL: a product in the Elasticsearch index "products", shaped for search.
 * It is a PROJECTION of the MySQL table owned by product-write-service, built by
 * ProductProjector from Debezium change events. It can always be rebuilt.
 * The annotations define the index mapping, which Spring Data creates at startup
 * when the index does not exist yet.
 */
@Document(indexName = "products")
@Setting(settingPath = "elasticsearch/product-settings.json", shards = 1, replicas = 0)
public class Product {

    /** Elasticsearch document id (generated by Elasticsearch on create). */
    @Id
    private String id;

    /** Business key, unique per product. Keyword = exact match, case-insensitive. */
    @Field(type = FieldType.Keyword, normalizer = "lowercase_normalizer")
    private String sku;

    /** Full-text searchable ("english" analyzer: "laptops" also matches "laptop"),
     *  plus a keyword sub-field "name.keyword" for sorting. */
    @MultiField(
            mainField = @Field(type = FieldType.Text, analyzer = "english"),
            otherFields = @InnerField(suffix = "keyword", type = FieldType.Keyword,
                    normalizer = "lowercase_normalizer", ignoreAbove = 256))
    private String name;

    @Field(type = FieldType.Text, analyzer = "english")
    private String description;

    @Field(type = FieldType.Keyword, normalizer = "lowercase_normalizer")
    private String brand;

    @Field(type = FieldType.Keyword, normalizer = "lowercase_normalizer")
    private String category;

    /** scaled_float with factor 100 stores prices exactly to 2 decimals (cents). */
    @Field(type = FieldType.Scaled_Float, scalingFactor = 100)
    private Double price;

    /** Memory in GB; null for products without RAM (headphones, monitors). */
    @Field(type = FieldType.Integer)
    private Integer ramGb;

    /** Average customer rating 0.0 - 5.0. */
    @Field(type = FieldType.Double)
    private Double rating;

    @Field(type = FieldType.Keyword, normalizer = "lowercase_normalizer")
    private List<String> tags = new ArrayList<>();

    @Field(type = FieldType.Date, format = DateFormat.epoch_millis)
    private Instant createdAt;

    @Field(type = FieldType.Date, format = DateFormat.epoch_millis)
    private Instant updatedAt;

    /**
     * MySQL row version of the data in this document. The projector uses it to skip
     * duplicate or outdated change events; clients send it back with updates (PUT).
     */
    @Field(type = FieldType.Long)
    private Long version;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getSku() {
        return sku;
    }

    public void setSku(String sku) {
        this.sku = sku;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public Double getPrice() {
        return price;
    }

    public void setPrice(Double price) {
        this.price = price;
    }

    public Integer getRamGb() {
        return ramGb;
    }

    public void setRamGb(Integer ramGb) {
        this.ramGb = ramGb;
    }

    public Double getRating() {
        return rating;
    }

    public void setRating(Double rating) {
        this.rating = rating;
    }

    public List<String> getTags() {
        return tags;
    }

    public void setTags(List<String> tags) {
        this.tags = tags;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }

    public Long getVersion() {
        return version;
    }

    public void setVersion(Long version) {
        this.version = version;
    }
}
